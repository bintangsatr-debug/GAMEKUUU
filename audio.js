function compileTrack(tr){
  if(tr._c)return tr._c;
  const out={};
  for(const k of['lead','arp','bass','drum']){
    const map=[];let p=0;
    for(const[n,d]of tr[k]){map[p]={n,d};p+=d}
    out[k]={map,len:p};
  }
  return(tr._c=out);
}
function playTone(ac,t0,f,dur,ty,vol){
  if(!f)return;
  const o=ac.createOscillator(),g=ac.createGain();
  o.type=ty;o.frequency.setValueAtTime(f,t0);
  g.gain.setValueAtTime(.0001,t0);
  g.gain.linearRampToValueAtTime(vol,t0+.007);
  g.gain.setValueAtTime(vol*.82,t0+Math.max(.012,dur*.72));
  g.gain.exponentialRampToValueAtTime(.0001,t0+dur*.96);
  o.connect(g);g.connect(ac.destination);o.start(t0);o.stop(t0+dur);
}
function playDrum(ac,t0,k){
  if(k=='K'){
    const o=ac.createOscillator(),g=ac.createGain();o.type='triangle';
    o.frequency.setValueAtTime(145,t0);o.frequency.exponentialRampToValueAtTime(42,t0+.085);
    g.gain.setValueAtTime(.18,t0);g.gain.exponentialRampToValueAtTime(.001,t0+.095);
    o.connect(g);g.connect(ac.destination);o.start(t0);o.stop(t0+.1);
  }else if((k=='S'||k=='H')&&noiseBuf){
    const s=ac.createBufferSource(),fl=ac.createBiquadFilter(),g=ac.createGain();
    s.buffer=noiseBuf;fl.type=k=='S'?'bandpass':'highpass';fl.frequency.value=k=='S'?1400:6500;
    const d=k=='S'?.1:.032;
    g.gain.setValueAtTime(k=='S'?.095:.042,t0);g.gain.exponentialRampToValueAtTime(.001,t0+d);
    s.connect(fl);fl.connect(g);g.connect(ac.destination);s.start(t0);s.stop(t0+d);
  }
}

let bgmTimer=null,bgmCur='',bgmStep=0,bgmNext=0;
function bgmStop(){if(bgmTimer){clearInterval(bgmTimer);bgmTimer=null}}
function bgmTick(){
  if(!S.snd||document.hidden){bgmStop();return}
  const ac=ensureAC();if(ac.state!=='running')return;
  const tr=BGM[bgmCur];if(!tr)return;
  const c=compileTrack(tr),sd=60/tr.bpm/4;
  if(bgmNext<ac.currentTime-.15)bgmNext=ac.currentTime+.03;
  while(bgmNext<ac.currentTime+.12){
    const L=c.lead.map[bgmStep%c.lead.len],A=c.arp.map[bgmStep%c.arp.len],B=c.bass.map[bgmStep%c.bass.len],D=c.drum.map[bgmStep%c.drum.len];
    if(L)playTone(ac,bgmNext,n2f(L.n),L.d*sd,'square',.052);
    if(A)playTone(ac,bgmNext,n2f(A.n),A.d*sd,'square',.026);
    if(B)playTone(ac,bgmNext,n2f(B.n),B.d*sd,'triangle',.085);
    if(D)playDrum(ac,bgmNext,D.n);
    bgmNext+=sd;bgmStep++;
  }
}
function bgmSync(){
  if(!S.snd||document.hidden||st=='pause'||st=='over'||st=='done'){bgmStop();return}
  const want=st=='play'?'lv'+lv:st=='cut'?'cut':'menu';
  if(bgmCur!==want){bgmCur=want;bgmStep=0;bgmNext=0}
  if(!bgmTimer){
    try{const ac=ensureAC();bgmNext=ac.currentTime+.04}catch(e){}
    bgmTimer=setInterval(bgmTick,25);
  }
}
